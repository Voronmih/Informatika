def count_letters(text): #TODO создаём функцию с 1 переменной для подсчёта количества каждой  из букв
    letter_count = {} #TODO создаём пустой словарь для количества каждой из букв
    for char in text: #TODO перебираем каждый символ в строке
        if char.isalpha(): #TODO если символ является буквой, выполняем следующее
            lower_char = char.lower() #TODO приводим букву к нижнему регистру
            letter_count[lower_char] = letter_count.get(lower_char, 0) + 1 #TODO добавляем в словарь текущее значение ключа (или 0) и затем прибавляем 1
    return letter_count #TODO возвращаем словарь

def calculate_frequency(letter_count): #TODO создём функцию для вычисления частоты каждой буквы
    total_letters = sum(letter_count.values()) #TODO суммируем все значения для получения общего количества букв
    frequency = {} #TODO создаём пустой словарь для частот каждой буквы
    for letter in letter_count: #TODO перебираем ключи словаря
        freq = letter_count[letter] / total_letters #TODO вычисляем частоту делением количества данной буквы на общее количство букв
        frequency[letter] = round(freq, 2) #TODO округляем до двух знаков после запятой
    return frequency #TODO возвращаем словарь
