counts = count_letters(main_str) #TODO выполняем функцию для данной переменной, получаем количество каждой из букв

frequencies = calculate_frequency(counts) #TODO выполняем вторую функцию и получаем частоты

for letter, freq in frequencies.items(): #TODO перебираем сразу две переменные в цикле
    print(f"{letter}: {freq:.2f}") #TODO выводим соответствующие переменные и округляем до 2 знаков после запятой
